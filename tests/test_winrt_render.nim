# test_winrt_render.nim — the rendering of a hand-built plan (doAssert-based).
# Run: nim r --verbosity:0 tests/test_winrt_render.nim  (or `nimble test`)

import std/[options, sequtils, strutils, tables]
import ../src/winmd/[guid, generator]
import ../src/winmd/winrt/[plan, render]

func named(name: string): AbiType =
  AbiType(kind: akNamed, name: name)

func pointerTo(target: AbiType): AbiType =
  AbiType(kind: akPointer, target: target)

func slot(name: string, parameters: varargs[Parameter]): VtableSlot =
  VtableSlot(name: name, parameters: some(@parameters))

let
  status = Declaration(
    kind: dkEnum,
    name: "AsyncStatus",
    underlying: named("int32"),
    isFlags: false,
    members: @[
      (name: "AsyncStatus_Started", value: "0'i32"),
      (name: "AsyncStatus_Completed", value: "1'i32"),
    ],
  )
  attributes = Declaration(
    kind: dkEnum,
    name: "FileAttributes",
    underlying: named("uint32"),
    isFlags: true,
    members: @[(name: "FileAttributes_ReadOnly", value: "1'u32")],
  )
  sample = Declaration(
    kind: dkStruct,
    name: "Sample",
    fields: @[
      (name: "Bytes", ty: AbiType(kind: akArray, element: named("uint8"), count: 4)),
      (name: "Context", ty: pointerTo(AbiType(kind: akVoid))),
    ],
  )
  vector = Declaration(
    kind: dkInterface,
    name: "IVector",
    genericParameters: @["T"],
    vtableName: "IVectorVtbl",
    iidName: "IID_IVector",
    guid: parseGuid("913337e9-11a1-4345-a3a2-4e7f956e222d"),
    slots: @[
      slot(
        "GetAt",
        (
          name: "this",
          ty: pointerTo(
            AbiType(kind: akInstantiation, definition: "IVector", args: @[named("T")])
          ),
        ),
        (name: "index", ty: named("uint32")),
        (name: "retval", ty: pointerTo(named("T"))),
      )
    ],
  )
  stringable = Declaration(
    kind: dkInterface,
    name: "IStringable",
    vtableName: "IStringableVtbl",
    iidName: "IID_IStringable",
    guid: parseGuid("96369f54-8eb6-48f0-abce-c1b211e627c3"),
    slots: @[
      slot(
        "ToString",
        (name: "this", ty: pointerTo(named("IStringable"))),
        (name: "retval", ty: pointerTo(named("HSTRING"))),
      ),
      VtableSlot(name: "Unspellable", parameters: none(seq[Parameter])),
    ],
  )
  handler = Declaration(
    kind: dkDelegate,
    name: "AsyncActionCompletedHandler",
    vtableName: "AsyncActionCompletedHandlerVtbl",
    iidName: "IID_AsyncActionCompletedHandler",
    guid: parseGuid("a4ed5c81-76c9-40bd-8be6-b1d90fb20ae7"),
    slots: @[
      slot(
        "Invoke",
        (name: "this", ty: pointerTo(named("AsyncActionCompletedHandler"))),
        (name: "asyncStatus", ty: named("AsyncStatus")),
      )
    ],
  )
  uri = Declaration(
    kind: dkClass,
    name: "Uri",
    className: "Windows.Foundation.Uri",
    classNameConst: "RuntimeClass_Windows_Foundation_Uri",
    defaultInterface: some(named("IUriRuntimeClass")),
  )
  launcher = Declaration(
    kind: dkClass,
    name: "Launcher",
    className: "Windows.System.Launcher",
    classNameConst: "RuntimeClass_Windows_System_Launcher",
    defaultInterface: none(AbiType),
  )

let handBuilt = Plan(
  modules: @[
    Module(
      kind: mkTypes,
      name: "winrttypes",
      imports: @["winrtbase"],
      declarations:
        @[status, attributes, sample, stringable, vector, handler, uri, launcher],
    ),
    Module(
      kind: mkNamespace,
      name: "foundation",
      namespaces: @["Windows.Foundation"],
      imports: @["winrtbase", "winrttypes"],
      declarations: @[stringable, vector, handler, uri, launcher],
    ),
  ],
  instantiationIids: @[
    (
      name: "IID_IVector_HSTRING",
      iid: parseGuid("98b9acc1-4b56-532e-ac73-03d5291cca90"),
    ),
    (
      name: "IID_IAsyncOperation_bool",
      iid: parseGuid("cdb5efb3-5788-509d-9be1-71ccb8a3362a"),
    ),
  ],
)

let modules = renderModules(handBuilt)
doAssert modules.mapIt(it.name) ==
  @["winrtbase", "winrtgenerics", "winrttypes", "foundation"]
let code = modules.mapIt((it.name, it.code)).toTable

# winrtbase as is, after the header
doAssert code["winrtbase"].startsWith(
  "## generated by winmd2nim from WinRT metadata — winrtbase (do not edit)\n## What every"
)

# every type: an enum as its integer and a const per member, an interface as
# the object a pointer to it points at, a class as its default interface
doAssert code["winrttypes"] == """
## generated by winmd2nim from WinRT metadata — winrttypes (do not edit)
import ./[winrtbase]
export winrtbase

{.pragma: mdtype, pure, bycopy, completeStruct.}
{.pragma: mdalias.}
{.pragma: mdinterface.}

type
  AsyncStatus* {.mdalias.} = int32
  FileAttributes* {.mdalias.} = uint32
  Sample* {.mdtype.} = object
    Bytes*: array[4, uint8]
    Context*: pointer
  IStringable* {.mdinterface.} = object
    lpVtbl*: ptr IInspectableVtbl
  IVector*[T] {.mdinterface.} = object
    lpVtbl*: ptr IInspectableVtbl
  AsyncActionCompletedHandler* {.mdinterface.} = object
    lpVtbl*: ptr IUnknownVtbl
  Uri* {.mdalias.} = IUriRuntimeClass
  Launcher* {.mdinterface.} = object
    lpVtbl*: pointer

const
  AsyncStatus_Started*: AsyncStatus = 0'i32
  AsyncStatus_Completed*: AsyncStatus = 1'i32
  FileAttributes_ReadOnly*: FileAttributes = 1'u32
"""

# a namespace: its vtables, parameterised ones first, its IIDs and class names
doAssert code["foundation"] == """
## generated by winmd2nim from WinRT metadata — foundation (do not edit)
import ./[winrtbase, winrttypes]
export winrtbase, winrttypes

{.pragma: mdvtbl, pure, inheritable.}
{.pragma: mdslot, stdcall, raises: [].}

type
  IVectorVtbl*[T] {.mdvtbl.} = object of IInspectableVtbl
    GetAt*: proc(this: ptr IVector[T], index: uint32, retval: ptr T): HRESULT {.mdslot.}
  IStringableVtbl* {.mdvtbl.} = object of IInspectableVtbl
    ToString*: proc(this: ptr IStringable, retval: ptr HSTRING): HRESULT {.mdslot.}
    Unspellable*: pointer # signature not mapped
  AsyncActionCompletedHandlerVtbl* {.mdvtbl.} = object of IUnknownVtbl
    Invoke*: proc(this: ptr AsyncActionCompletedHandler, asyncStatus: AsyncStatus): HRESULT {.mdslot.}

const
  IID_IStringable*: GUID = guid"96369f54-8eb6-48f0-abce-c1b211e627c3"
  IID_IVector*: GUID = guid"913337e9-11a1-4345-a3a2-4e7f956e222d"
  IID_AsyncActionCompletedHandler*: GUID = guid"a4ed5c81-76c9-40bd-8be6-b1d90fb20ae7"
  RuntimeClass_Windows_Foundation_Uri*: string = "Windows.Foundation.Uri"
  RuntimeClass_Windows_System_Launcher*: string = "Windows.System.Launcher"

template vtbl*(this: ptr IStringable): ptr IStringableVtbl = cast[ptr IStringableVtbl](this.lpVtbl)
template vtbl*[T](this: ptr IVector[T]): ptr IVectorVtbl[T] = cast[ptr IVectorVtbl[T]](this.lpVtbl)
template vtbl*(this: ptr AsyncActionCompletedHandler): ptr AsyncActionCompletedHandlerVtbl = cast[ptr AsyncActionCompletedHandlerVtbl](this.lpVtbl)
"""

# the instantiation IIDs, sorted
doAssert code["winrtgenerics"] == """
## generated by winmd2nim from WinRT metadata — winrtgenerics (do not edit)
import ./[winrtbase]
export winrtbase

const
  IID_IAsyncOperation_bool*: GUID = guid"cdb5efb3-5788-509d-9be1-71ccb8a3362a"
  IID_IVector_HSTRING*: GUID = guid"98b9acc1-4b56-532e-ac73-03d5291cca90"
"""

# no declarations, no sections
let empty = Module(kind: mkTypes, name: "winrttypes", imports: @["winrtbase"])
doAssert renderModules(Plan(modules: @[empty]))[2].code == """
## generated by winmd2nim from WinRT metadata — winrttypes (do not edit)
import ./[winrtbase]
export winrtbase

{.pragma: mdtype, pure, bycopy, completeStruct.}
{.pragma: mdalias.}
{.pragma: mdinterface.}
"""

# over a reference: its winrtbase, not one of this output's own, and its
# types imported qualified by the modules that name one
let over = renderModules(
  Plan(
    modules: @[
      Module(
        kind: mkTypes,
        name: "winrttypes",
        imports: @["winrtbase"],
        declarations: @[
          Declaration(
            kind: dkStruct,
            name: "Placement",
            fields: @[(name: "Origin", ty: named("winrt.Point"))],
          )
        ],
      ),
      Module(
        kind: mkNamespace,
        name: "microsoft_ui",
        imports: @["winrtbase", "winrttypes"],
        declarations: @[
          Declaration(
            kind: dkClass,
            name: "Placer",
            className: "Microsoft.UI.Placer",
            classNameConst: "RuntimeClass_Microsoft_UI_Placer",
          )
        ],
      ),
    ],
    base: "winrt/abi",
    qualified: @[(alias: "winrt", path: "winrt/abi")],
  )
)
doAssert over.mapIt(it.name) == @["winrtgenerics", "winrttypes", "microsoft_ui"]
doAssert over[0].code.endsWith "import winrt/abi/winrtbase\nexport winrtbase\n"
doAssert "\nimport winrt/abi/winrtbase\nexport winrtbase\n" &
  "from winrt/abi/winrttypes as winrt import nil\n" in over[1].code
doAssert "Origin*: winrt.Point" in over[1].code
# names nothing of the reference's: no import to go unused
doAssert "\nimport winrt/abi/winrtbase\nimport ./[winrttypes]\n" &
  "export winrtbase, winrttypes\n\n" in over[2].code
doAssert "import nil" notin over[2].code

echo "test_winrt_render: all assertions passed"
