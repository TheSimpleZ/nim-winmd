const baseModule = staticRead("winrtbase.nim").replace("\r\n", "\n")
  ## winrtbase as it is written out.

func lines(xs: openArray[string]): string =
  ## `xs`, each followed by a newline.
  xs.mapIt(it & "\n").join

func paragraph(xs: seq[string]): string =
  ## `xs` after a blank line, each on a line of its own; nothing when there
  ## are none.
  if xs.len > 0:
    lines(@[""] & xs)
  else:
    ""

func section(keyword: string, xs: seq[string]): string =
  ## A `type` or `const` section of `xs` after a blank line; nothing when
  ## there are none (an empty section does not parse).
  if xs.len > 0:
    paragraph(@[keyword] & xs)
  else:
    ""

func header(name: string, about = ""): string =
  ## The first line of a module, its doc comment, and a second when there is
  ## more to say `about` it.
  let first =
    fmt"## generated by winmd2nim from WinRT metadata — {name} (do not edit)"
  if about.len > 0:
    first & "\n## " & about
  else:
    first

func spell(t: AbiType): string =
  ## How Nim writes `t`: `int32`, `ptr Uri`, `ptr IVector[HSTRING]`,
  ## `array[4, uint8]`; a pointer to nothing is a `pointer`.
  case t.kind
  of akVoid:
    "void"
  of akNamed:
    t.name
  of akPointer:
    if t.target.kind == akVoid:
      "pointer"
    else:
      "ptr " & spell(t.target)
  of akInstantiation:
    let args = t.args.map(spell).join(", ")
    fmt"{t.definition}[{args}]"
  of akArray:
    fmt"array[{t.count}, {spell(t.element)}]"

func hasVtable(d: Declaration): bool =
  ## An interface or delegate: a type with a vtable and an IID.
  d.kind in {dkInterface, dkDelegate}

func isParameterised(d: Declaration): bool =
  ## A parameterised interface or delegate, `IVector[T]`.
  d.hasVtable and d.genericParameters.len > 0

func generics(d: Declaration): string =
  ## The generic parameters of interface or delegate `d`, `[T]` or `[K, V]`;
  ## "" when it has none.
  if d.genericParameters.len > 0:
    let list = d.genericParameters.join(", ")
    fmt"[{list}]"
  else:
    ""

