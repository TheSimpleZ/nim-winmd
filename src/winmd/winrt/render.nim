const
  structPragma = "{.pragma: mdtype, pure, bycopy, completeStruct.}"
  aliasPragma = "{.pragma: mdalias.}"
  interfacePragma = "{.pragma: mdinterface.}"
  vtablePragma = "{.pragma: mdvtbl, pure, inheritable.}"

func declarationsFile(k: Module): string =
  ## winrttypes, or the module of a namespace (or of the namespaces of a
  ## cycle): its declarations in one type section, then their consts (IIDs,
  ## runtime class names, enum members), then what its enums borrow from
  ## their integers.
  ##
  ## The parameterised interfaces come first, each object followed by its
  ## vtable: instantiating `TypedEventHandler[A, B]` in a slot or a class
  ## alias before the vtable its body points to has been seen is an internal
  ## error in Nim 2.2.
  let parameterised = k.declarations.filterIt(it.isParameterised)
  let others = k.declarations.filterIt(not it.isParameterised)
  let types =
    parameterised.mapIt(typeDeclaration(it) & vtableDeclaration(it)).concat &
    others.map(typeDeclaration).concat &
    others.filterIt(it.hasVtable).map(vtableDeclaration).concat
  let namespaces = k.namespaces.join(", ")
  let about =
    if k.namespaces.len > 1:
      fmt"the namespaces {namespaces} refer to each other in a cycle, and share this module"
    else:
      ""
  let pragmas =
    if k.kind == mkTypes: # enums and structs only
      @[structPragma]
    else:
      @[structPragma, aliasPragma, interfacePragma, vtablePragma]
  let imports = k.imports.join(", ")
  fmt"""
{header(k.name, about)}
import ./[{imports}]
export {imports}
""" &
    paragraph(pragmas) & section("type", types) &
    section("const", k.declarations.map(constDeclarations).concat) &
    lines(k.declarations.map(enumFuncs).concat)

func shimFile(k: Module): string =
  ## A namespace of a cycle: re-exports the module it shares with the others.
  let (namespace, group) = (k.namespaces[0], k.imports[0])
  let about =
    fmt"{namespace} shares {group} with the namespaces it refers to in a cycle"
  fmt"""
{header(k.name, about)}
import ./{group}
export {group}
"""

func genericsFile(p: Plan): string =
  ## winrtgenerics: the IID of every instantiation the metadata uses, sorted
  ## by name.
  let consts = p.instantiationIids.sortedByIt(it.name).mapIt(
      fmt"  {it.name}*: GUID = {nimLiteral(it.iid)}"
    )
  fmt"""
{header("winrtgenerics")}
import ./winrtbase
export winrtbase
""" &
    section("const", consts)

func moduleFile(k: Module): string =
  ## Module `k` as it is written out.
  case k.kind
  of mkTypes, mkNamespace:
    declarationsFile(k)
  of mkShim:
    shimFile(k)

func renderModules*(p: Plan): seq[GenModule] =
  ## Every module to write out, each its name (the `.nim` file's, without the
  ## extension) and its Nim source: winrtbase, winrtgenerics, then the modules
  ## of the plan.
  @[
    GenModule(name: "winrtbase", code: header("winrtbase") & "\n" & baseModule),
    GenModule(name: "winrtgenerics", code: genericsFile(p)),
  ] & p.modules.mapIt(GenModule(name: it.name, code: moduleFile(it)))
