# render.nim — renders the plan (winrt/plan) as the Nim source of the WinRT
# modules, from the plan alone. The plan has settled what each type is called, what it holds
# with every reference resolved, and which module declares it; this lays it
# out in Nim: the type sections with their enums, objects and vtables, then the
# consts, and the imports that tie the modules together.

