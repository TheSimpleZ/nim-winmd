func slotType(s: VtableSlot): string =
  ## A vtable slot's type: the method as the ABI calls it; one the metadata
  ## cannot spell stays a `pointer`.
  if s.parameters.isNone:
    return "pointer # signature not mapped"
  let list = s.parameters.get.mapIt(fmt"{it.name}: {spell(it.ty)}").join(", ")
  fmt"proc({list}): HRESULT {{.stdcall.}}"

func typeDeclaration(d: Declaration): seq[string] =
  ## The declaration of `d` in a type section.
  case d.kind
  of dkEnum:
    # a distinct integer: its members are consts (constDeclarations), its
    # operations borrowed (enumFuncs)
    @[fmt"  {d.name}* = distinct {spell(d.underlying)}"]
  of dkStruct:
    @[fmt"  {d.name}* {{.mdtype.}} = object"] &
      d.fields.mapIt(fmt"    {it.name}*: {spell(it.ty)}")
  of dkInterface, dkDelegate:
    # the object behind a pointer to an interface or delegate
    @[
      fmt"  {d.name}*{generics(d)} {{.mdinterface.}} = object",
      fmt"    lpVtbl*: ptr {d.vtableName}{generics(d)}",
    ]
  of dkClass:
    if d.defaultInterface.isSome:
      # a runtime class: what crosses the ABI is its default interface
      @[fmt"  {d.name}* {{.mdalias.}} = {spell(d.defaultInterface.get)}"]
    else:
      # a static class: no default interface, and no instances
      @[fmt"  {d.name}* {{.mdinterface.}} = object", "    lpVtbl*: pointer"]

func vtableDeclaration(d: Declaration): seq[string] =
  ## The vtable of interface or delegate `d`: its base, then its methods in
  ## slot order.
  let parent = if d.kind == dkDelegate: "IUnknownVtbl" else: "IInspectableVtbl"
  @[fmt"  {d.vtableName}*{generics(d)} {{.mdvtbl.}} = object of {parent}"] &
    d.slots.mapIt(fmt"    {it.name}*: {slotType(it)}")

func constDeclarations(d: Declaration): seq[string] =
  ## The consts of `d`: the IID of an interface or delegate, the name of a
  ## runtime class, or the members of an enum.
  case d.kind
  of dkInterface, dkDelegate:
    @[fmt"  {d.iidName}*: GUID = {nimLiteral(d.guid)}"]
  of dkClass:
    @[fmt"  {d.classNameConst}*: string = {escape(d.className)}"]
  of dkEnum:
    d.members.mapIt(fmt"  {it.name}*: {d.name} = {d.name}({it.value})")
  of dkStruct:
    @[]

func enumFuncs(d: Declaration): seq[string] =
  ## What enum `d` borrows from its integer, after a blank line: comparing and
  ## printing, and for a [Flags] enum combining its members and testing for
  ## them (`NetworkTypes_Internet in types`); nothing for any other type.
  if d.kind != dkEnum:
    return
  let t = d.name
  result = @[
    "",
    fmt"func `==`*(a, b: {t}): bool {{.borrow.}}",
    fmt"func `$`*(a: {t}): string {{.borrow.}}",
  ]
  if d.isFlags:
    let integer = spell(d.underlying)
    result.add @[
      fmt"func `or`*(a, b: {t}): {t} {{.borrow.}}",
      fmt"func `and`*(a, b: {t}): {t} {{.borrow.}}",
      fmt"func `not`*(a: {t}): {t} {{.borrow.}}",
      fmt"func contains*(a, b: {t}): bool =",
      "  ## True if every bit of `b` is set in `a`.",
      fmt"  ({integer}(a) and {integer}(b)) == {integer}(b)",
    ]

